#!/usr/bin/env python3
"""Make punchout/src/pipeline_seed.inc from pipelines.keys files.

The renderer remembers every pipeline the game used in pipelines.keys (beside
the settings) and compiles them all as the game starts. The seed is the same
records built into the game, so a first run starts with the ones seen while
making this build. It holds no game data beyond GX register values.

  make_pipeline_seed.py <out.inc> <pipelines.keys>...

Records found in several files are kept once. With no files, the seed is the
header alone (no pipelines).
"""
import struct
import sys

MAGIC = b"POPKEYS1"


def records(data):
    """(kind, bytes) records of one pipelines.keys file, or [] if it isn't one."""
    if len(data) < 16 or data[:8] != MAGIC:
        return [], None
    key_size, words = struct.unpack_from("<II", data, 8)
    one = 1 + key_size
    out, p = [], 16
    while p + one <= len(data):
        kind = data[p]
        size = one if kind == 0 else one + 4 * words
        if kind not in (0, 1) or p + size > len(data):
            break
        out.append(bytes(data[p:p + size]))
        p += size
    return out, (key_size, words)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    seen, ordered, header = set(), [], None
    for path in sys.argv[2:]:
        recs, sizes = records(open(path, "rb").read())
        if sizes is None:
            sys.exit(f"{path}: not a pipelines.keys file")
        if header is None:
            header = sizes
        elif header != sizes:
            sys.exit(f"{path}: from a build with other key sizes")
        for r in recs:
            if r not in seen:
                seen.add(r)
                ordered.append(r)
    key_size, words = header if header else (12, 70)
    blob = MAGIC + struct.pack("<II", key_size, words) + b"".join(ordered)
    uber = sum(1 for r in ordered if r[0] == 0)
    with open(sys.argv[1], "w") as f:
        f.write("// Generated by tools/make_pipeline_seed.py: the pipelines seen while making this build\n")
        f.write(f"// ({uber} of the ubershader's, {len(ordered) - uber} specialised). The renderer compiles them as the game starts.\n")
        f.write("static const unsigned char kPipelineSeed[] = {\n")
        for i in range(0, len(blob), 24):
            f.write("    " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 24]) + ",\n")
        f.write("};\n")
    print(f"{sys.argv[1]}: {uber} of the ubershader's, {len(ordered) - uber} specialised, {len(blob)} bytes")


if __name__ == "__main__":
    main()
