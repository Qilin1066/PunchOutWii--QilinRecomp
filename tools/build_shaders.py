#!/usr/bin/env python3
"""Compile punchout/shaders/ to SPIR-V and write punchout/src/shaders.inc.

The generated file is committed, so building the game needs no shader
compiler; run this (it needs glslangValidator) after changing a shader.

The header records a SHA-256 of every source in punchout/shaders/. `--check`
(CI) fails if that hash doesn't match the sources, meaning someone changed a
shader without regenerating. It needs no compiler, because SPIR-V bytes
differ between glslang versions. If glslangValidator is installed, it also
compiles each shader, so a broken one fails too.
"""
import hashlib
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "punchout/shaders"
TARGET = ROOT / "punchout/src/shaders.inc"
SHADERS = ["gx.vert", "gx.frag", "fullscreen.vert", "clear.frag", "copy.frag"]


def sources_hash() -> str:
    h = hashlib.sha256()
    for f in sorted(SRC.iterdir()):
        if f.is_file():
            h.update(f.name.encode() + b"\0")
            h.update(f.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return h.hexdigest()


def compile_one(src: pathlib.Path, out: pathlib.Path) -> bytes:
    subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", "-o", str(out), str(src)],
                   check=True, stdout=subprocess.DEVNULL)
    return out.read_bytes()


def check() -> int:
    stamp = f"// Sources: {sources_hash()}"
    lines = TARGET.read_text().splitlines() if TARGET.exists() else []
    if stamp not in lines[:4]:
        print("punchout/src/shaders.inc is out of date: run tools/build_shaders.py", file=sys.stderr)
        return 1
    if shutil.which("glslangValidator"):
        with tempfile.TemporaryDirectory() as tmp:
            for name in SHADERS:
                compile_one(SRC / name, pathlib.Path(tmp) / "out.spv")
    else:
        print("glslangValidator not found: checked the hash only")
    return 0


def main() -> int:
    if "--check" in sys.argv:
        return check()
    lines = ["// Generated by tools/build_shaders.py from punchout/shaders/: do not edit.",
             f"// Sources: {sources_hash()}", "#pragma once", "#include <cstdint>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for name in SHADERS:
            b = compile_one(SRC / name, pathlib.Path(tmp) / "out.spv")
            words = struct.unpack(f"<{len(b) // 4}I", b)
            ident = "k" + "".join(p.capitalize() for p in name.replace(".", "_").split("_"))
            lines.append(f"inline constexpr uint32_t {ident}[] = {{")
            for i in range(0, len(words), 8):
                lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
            lines.append("};")
    TARGET.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
